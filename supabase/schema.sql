grant execute on function public.available_slots(bigint, date) to authenticated;

revoke all on function public.create_booking(bigint, text, timestamptz[], timestamptz, timestamptz) from public;
grant execute on function public.create_booking(bigint, text, timestamptz[], timestamptz, timestamptz) to authenticated;

create or replace function public.cancel_booking(p_booking_id bigint)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not exists (
    select 1 from public.bookings
    where id = p_booking_id and member_id = auth.uid()
      and status in ('PENDING', 'APPROVED')
  ) then
    raise exception 'Booking kan ikke annulleres';
  end if;
  update public.bookings
  set status = 'CANCELLED', updated_at = now()
  where id = p_booking_id;
  delete from public.booking_slots where booking_id = p_booking_id;
end;
$$;

create or replace function public.modify_booking_team_name(p_booking_id bigint, p_team_name text)
returns void language plpgsql security definer set search_path = public as $$
begin
  if trim(coalesce(p_team_name, '')) = '' then
    raise exception 'Holdnavn er påkrævet';
  end if;
  if not exists (
    select 1 from public.bookings
    where id = p_booking_id and member_id = auth.uid()
      and status in ('PENDING', 'APPROVED')
  ) then
    raise exception 'Booking kan ikke redigeres';
  end if;
  update public.bookings
  set team_name = trim(p_team_name), updated_at = now()
  where id = p_booking_id;
end;
$$;

create or replace function public.approve_booking(p_booking_id bigint)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception 'Kun administrator'; end if;
  update public.bookings set status = 'APPROVED', updated_at = now()
  where id = p_booking_id and status = 'PENDING';
end;
$$;

create or replace function public.reject_booking(p_booking_id bigint)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception 'Kun administrator'; end if;
  update public.bookings set status = 'REJECTED', updated_at = now()
  where id = p_booking_id and status = 'PENDING';
  delete from public.booking_slots where booking_id = p_booking_id;
end;
$$;

create or replace function public.set_member_status(p_member_id uuid, p_status text)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception 'Kun administrator'; end if;
  if p_status not in ('APPROVED', 'REJECTED') then
    raise exception 'Ugyldig medlemsstatus';
  end if;
  update public.profiles set account_status = p_status where id = p_member_id;
end;
$$;
